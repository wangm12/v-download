export const APP_LOCALES = ['en', 'zh-CN', 'zh-TW'] as const
export type AppLanguage = (typeof APP_LOCALES)[number]

type DeepString<T> = {
  [K in keyof T]: T[K] extends string ? string : DeepString<T[K]>
}

export const UI_LANGUAGE_PREFERENCES = ['system', ...APP_LOCALES] as const
export type UiLanguagePreference = (typeof UI_LANGUAGE_PREFERENCES)[number]

export function resolveAppLanguage(value: unknown): AppLanguage {
  return value === 'zh-CN' || value === 'zh-TW' ? value : 'en'
}

export function isUiLanguagePreference(value: unknown): value is UiLanguagePreference {
  return value === 'system' || value === 'en' || value === 'zh-CN' || value === 'zh-TW'
}

export function normalizeUiLanguagePreference(value: unknown): UiLanguagePreference {
  return isUiLanguagePreference(value) ? value : 'en'
}

export function resolveUiLanguage(preference: unknown, systemLocale: string): AppLanguage {
  if (preference === 'system') return mapSystemLocale(systemLocale)
  return resolveAppLanguage(preference)
}

export function mapSystemLocale(locale: string): AppLanguage {
  const normalized = locale.toLowerCase()
  if (normalized.startsWith('zh-tw') || normalized.startsWith('zh-hk') || normalized.includes('hant')) return 'zh-TW'
  if (normalized.startsWith('zh')) return 'zh-CN'
  return 'en'
}

export function flattenCatalogKeys(node: unknown, prefix = ''): string[] {
  if (!node || typeof node !== 'object') return prefix ? [prefix] : []
  const keys: string[] = []
  for (const [name, value] of Object.entries(node as Record<string, unknown>)) {
    const path = prefix ? `${prefix}.${name}` : name
    if (value && typeof value === 'object') keys.push(...flattenCatalogKeys(value, path))
    else keys.push(path)
  }
  return keys
}

function lookup(node: unknown, key: string): string | undefined {
  let current: unknown = node
  for (const part of key.split('.')) {
    if (!current || typeof current !== 'object' || !(part in current)) return undefined
    current = (current as Record<string, unknown>)[part]
  }
  return typeof current === 'string' ? current : undefined
}

function interpolate(template: string, vars?: Record<string, string | number>): string {
  if (!vars) return template
  return template.replace(/\{\{(\w+)\}\}/g, (_, name: string) => (
    vars[name] === undefined ? `{{${name}}}` : String(vars[name])
  ))
}

export function translate(
  locale: AppLanguage,
  key: string,
  vars?: Record<string, string | number>
): string {
  const value = lookup(catalogs[locale], key) ?? lookup(catalogs.en, key) ?? key
  return interpolate(value, vars)
}

