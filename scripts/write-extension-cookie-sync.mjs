/**
 * Writes extension/cookie-sync-domains.js from the built @v-download/shared package
 * so the MV3 service worker can importScripts() a single source of truth for domains.
 */
import { writeFileSync } from 'fs'
import { createRequire } from 'module'
import { dirname, join } from 'path'
import { fileURLToPath } from 'url'

const require = createRequire(import.meta.url)
const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const sharedEntry = join(root, 'packages/shared/dist/cookie-sync-domains.js')

const { COOKIE_SYNC_DOMAINS } = require(sharedEntry)

const banner =
  '// AUTO-GENERATED by `npm run sync:extension-constants`. Edit packages/shared/src/cookie-sync-domains.ts instead.\n'

const body = `${banner}globalThis.COOKIE_SYNC_DOMAINS = ${JSON.stringify([...COOKIE_SYNC_DOMAINS])};\n`

const outPath = join(root, 'extension/cookie-sync-domains.js')
writeFileSync(outPath, body, 'utf-8')
console.log('Wrote', outPath)
