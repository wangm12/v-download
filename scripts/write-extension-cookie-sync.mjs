/**
 * Writes extension/cookie-sync-domains.js from the built @v-download/shared package
 * so the MV3 service worker can importScripts() a single source of truth for domains.
 */
import { readFileSync, writeFileSync } from 'fs'
import { createRequire } from 'module'
import { dirname, join } from 'path'
import { fileURLToPath } from 'url'

const require = createRequire(import.meta.url)
const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const sharedEntry = join(root, 'packages/shared/dist/cookie-sync-domains.js')

const { COOKIE_SYNC_DOMAINS } = require(sharedEntry)

const banner =
  '// AUTO-GENERATED by `npm run sync:extension-constants`. Edit packages/shared/src/cookie-sync-domains.ts instead.\n'

const body = `${banner}globalThis.COOKIE_SYNC_DOMAINS = ${JSON.stringify([...COOKIE_SYNC_DOMAINS])};\n`

const outPath = join(root, 'extension/cookie-sync-domains.js')
writeFileSync(outPath, body, 'utf-8')
console.log('Wrote', outPath)

const ts = require('typescript')
for (const [name, globalName] of [['download-selection', 'VDownloadSelection'], ['media-source-context', 'VDownloadSourceContext']]) {
  const source = readFileSync(join(root, `packages/shared/src/${name}.ts`), 'utf8')
  const compiled = ts.transpileModule(source, { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.CommonJS } }).outputText
  writeFileSync(join(root, `extension/${name}.js`), `// AUTO-GENERATED by npm run sync:extension-constants; edit packages/shared/src/${name}.ts.\n` +
    `globalThis.${globalName} = (() => { const exports = {};\n` + compiled + '\nreturn exports; })();\n', 'utf8')
}
