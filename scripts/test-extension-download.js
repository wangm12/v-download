const context = { globalThis: {}, Set, Math }
vm.runInNewContext(fs.readFileSync('extension/download-transport.js', 'utf8'), context)
const transport = context.globalThis.VDownloadDownloadTransport
assert.strictEqual(transport.isTransientStatus(503), true)
assert.strictEqual(transport.isTransientStatus(502), true)
assert.strictEqual(transport.isTransientStatus(504), true)
assert.strictEqual(transport.isTransientStatus(401), false)
assert.strictEqual(transport.isTransientStatus(500), false)
assert.strictEqual(transport.shouldRetry({ error: { name: 'TypeError' }, attempt: 0, maxAttempts: 3 }), true)
assert.strictEqual(transport.shouldRetry({ status: 503, attempt: 1, maxAttempts: 3 }), true)
assert.strictEqual(transport.shouldRetry({ status: 503, attempt: 2, maxAttempts: 3 }), false)
assert.strictEqual(transport.shouldRetry({ status: 404, attempt: 0, maxAttempts: 3 }), false)
assert.strictEqual(transport.shouldRetry({ status: 500, attempt: 0, maxAttempts: 3 }), false)
assert.strictEqual(transport.shouldRetry({ error: { name: 'Error' }, attempt: 0, maxAttempts: 3 }), false)
assert.deepStrictEqual([0, 1, 2].map(transport.retryDelay), [250, 500, 1000])
const assertFailure = (input, category, retryable) => {
  const result = transport.classifyFailure(input)
  assert.strictEqual(result.category, category)
  assert.strictEqual(result.retryable, retryable)
}
assertFailure({ status: 503 }, 'app-unavailable', true)
assertFailure({ error: { name: 'TypeError' } }, 'network-retryable', true)
assertFailure({ status: 401 }, 'authorization-required', true)
assertFailure({ status: 422 }, 'invalid-media-candidate', false)
const mergedResults = transport.mergeRetryResults(
  [{ ok: true, id: 'a' }, { ok: false, id: 'b' }, { ok: false, id: 'c' }],
  [1, 2],
  [{ ok: true, id: 'b2' }, { ok: false, id: 'c2' }]
)
assert.strictEqual(mergedResults.length, 3)
assert.strictEqual(mergedResults[0].id, 'a')
assert.strictEqual(mergedResults[1].id, 'b2')
assert.strictEqual(mergedResults[1].ok, true)
assert.strictEqual(mergedResults[2].id, 'c2')
assert.strictEqual(mergedResults[2].category, 'network-retryable')
const mergedCategorizedFailure = transport.mergeRetryResults(
  [{ ok: false, status: 503, category: 'app-unavailable', retryable: true, error: 'HTTP 503' }],
  [0],
  [{ ok: false, status: 0, error: 'Not sent' }]
)[0]
assert.strictEqual(mergedCategorizedFailure.category, 'app-unavailable')
assert.strictEqual(mergedCategorizedFailure.retryable, true)
const mergedClassifiedFallback = transport.mergeRetryResults(
  [{ ok: false, category: 'network-retryable', retryable: true }],
  [0],
  [{ ok: false, status: 503, error: 'HTTP 503' }]
)[0]
assert.strictEqual(mergedClassifiedFallback.category, 'app-unavailable')
assert.strictEqual(mergedClassifiedFallback.retryable, true)

