const assert = require('assert')
const fs = require('fs')
const vm = require('vm')

const context = { globalThis: {}, Set, Math }
vm.runInNewContext(fs.readFileSync('extension/download-transport.js', 'utf8'), context)
const transport = context.globalThis.VDownloadDownloadTransport
assert.strictEqual(transport.isTransientStatus(503), true)
assert.strictEqual(transport.isTransientStatus(502), true)
assert.strictEqual(transport.isTransientStatus(504), true)
assert.strictEqual(transport.isTransientStatus(401), false)
assert.strictEqual(transport.isTransientStatus(500), false)
assert.strictEqual(transport.shouldRetry({ error: { name: 'TypeError' }, attempt: 0, maxAttempts: 3 }), true)
assert.strictEqual(transport.shouldRetry({ status: 503, attempt: 1, maxAttempts: 3 }), true)
assert.strictEqual(transport.shouldRetry({ status: 503, attempt: 2, maxAttempts: 3 }), false)
assert.strictEqual(transport.shouldRetry({ status: 404, attempt: 0, maxAttempts: 3 }), false)
assert.strictEqual(transport.shouldRetry({ status: 500, attempt: 0, maxAttempts: 3 }), false)
assert.strictEqual(transport.shouldRetry({ error: { name: 'Error' }, attempt: 0, maxAttempts: 3 }), false)
assert.deepStrictEqual([0, 1, 2].map(transport.retryDelay), [250, 500, 1000])

const overlay = fs.readFileSync('extension/content-video-overlay.js', 'utf8')
const background = fs.readFileSync('extension/background.js', 'utf8')
assert.match(overlay, /Sending…/)
assert.match(overlay, /Added to queue/)
assert.match(overlay, /Error — retry/)
assert.match(overlay, /previous === 'sending' \|\| previous === 'queued'/)
assert.match(overlay, /chrome\.runtime\.lastError/)
assert.match(background, /Missing item or url/)
assert.match(background, /maxAttempts = 3/)
assert.match(background, /DT\.isTransientStatus/)
assert.match(background, /launchWakeToFocusApp\(tabId, \{ force: true \}\)/)
console.log('extension download: transient retry, cold wake, duplicate guard, and visible states verified')
