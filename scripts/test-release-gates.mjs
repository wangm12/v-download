assert.notEqual(r.status, 0); assert.match(r.stderr, /notarytool|updater|extension ID/i)
writeFileSync(metadata, JSON.stringify({ provider: 'mock', version: '9.9.9' }))
r = run(base)
assert.notEqual(r.status, 0); assert.match(r.stderr, /version mismatch/i)
