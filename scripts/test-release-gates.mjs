import assert from 'node:assert/strict'
import { spawnSync } from 'node:child_process'
import { join } from 'node:path'
import { mkdtempSync, writeFileSync, rmSync, readFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { mergeLatestMac, parseLatestMac, stringifyLatestMac } from './merge-latest-mac.mjs'
const root = new URL('..', import.meta.url).pathname
const run = (env) => spawnSync(process.execPath, [join(root, 'scripts/verify-release.mjs')], { cwd: root, env: { ...process.env, ...env }, encoding: 'utf8' })
const validId = 'abcdefghijklmnopabcdefghijklmnop'
const temp = mkdtempSync(join(tmpdir(), 'v-download-release-fixture-'))
const metadata = join(temp, 'updates.json')
const base = { RELEASE_DRY_RUN: '1', RELEASE_ARCH: 'arm64', RELEASE_ENGINE_VERIFY_MOCK: '1', RELEASE_UPDATER_MOCK: '1', CHROME_EXTENSION_ID: validId, PUBLISH_PROVIDER: 'mock', RELEASE_UPDATE_METADATA: metadata }
writeFileSync(metadata, JSON.stringify({ provider: 'mock', version: '1.1.7' }))
let r = run(base)
assert.equal(r.status, 0, r.stderr); assert.match(r.stdout, /mock\/dry-run mode \(not a release claim\)/)
 r = run({ RELEASE_DRY_RUN: '1', RELEASE_ARCH: 'arm64' })
assert.notEqual(r.status, 0); assert.match(r.stderr, /extension ID|updater/i)
r = run({ RELEASE_DRY_RUN: '1', RELEASE_ARCH: 'bogus' })
assert.notEqual(r.status, 0); assert.match(r.stderr, /RELEASE_ARCH/)
r = run({ RELEASE_ARCH: 'arm64', RELEASE_ARTIFACT: '/tmp/missing-v-download.app' })
assert.notEqual(r.status, 0); assert.match(r.stderr, /signing|notarization|macOS-first|artifact/i)
r = run({ RELEASE_DRY_RUN: '1', RELEASE_ARCH: 'arm64', RELEASE_ARTIFACT: '/tmp/mock.app', RELEASE_ARTIFACT_ARCH: 'x86_64', RELEASE_ENGINE_VERIFY_MOCK: '1', RELEASE_ENGINE_ROOT: '/tmp/missing-engine-fixture' })
assert.notEqual(r.status, 0); assert.match(r.stderr, /architecture|checksum|sidecar|plugin|manifest/i)
r = run({ RELEASE_DRY_RUN: '1', RELEASE_ARCH: 'arm64', RELEASE_NOTARY_INFO_JSON: JSON.stringify({ status: 'Invalid' }) })
assert.notEqual(r.status, 0); assert.match(r.stderr, /notarytool|updater|extension ID/i)
writeFileSync(metadata, JSON.stringify({ provider: 'mock', version: '9.9.9' }))
r = run(base)
assert.notEqual(r.status, 0); assert.match(r.stderr, /version mismatch/i)
rmSync(temp, { recursive: true, force: true })
console.log('release gate offline fixtures passed (missing credentials, invalid artifact arch, engine/sidecar/plugin checks, non-Accepted notary path, updater implementation, extension ID)')
const verifierSource = readFileSync(join(root, 'scripts/verify-release.mjs'), 'utf8')
assert.match(verifierSource, /Contents.*MacOS/)
assert.match(verifierSource, /codesign.*target\.verificationTarget/)
assert.match(verifierSource, /stapler.*target\.staplerTarget/)
assert.match(verifierSource, /contains no identifiable app bundle/)
assert.match(verifierSource, /bgutil-provider.*metadata version mismatch[\s\S]*engineManifest\.engines\?\.\['bgutil-provider'\]\?\.version/)
assert.match(verifierSource, /bgutil-plugin.*metadata version mismatch[\s\S]*engineManifest\.engines\?\.\['bgutil-provider'\]\?\.plugin\?\.version/)
const builderConfig = readFileSync(join(root, 'electron-builder.yml'), 'utf8')
const builderSource = readFileSync(join(root, 'scripts/build-mac-release.mjs'), 'utf8')
const verifySource = readFileSync(join(root, 'scripts/verify-release.mjs'), 'utf8')
assert.match(builderConfig, /npmRebuild: false/)
assert.match(builderConfig, /!resources\/engines\/\*\*\/*/)
assert.match(builderConfig, /\.release-staging\/current\/engines/)
assert.match(builderConfig, /afterPack:\s*\.\/scripts\/after-pack\.mjs/)
assert.match(builderSource, /RELEASE_ARCH: arch/)
assert.match(builderSource, /cp\(join\(engineSource, key\)/)
assert.match(builderSource, /staging contains unexpected engine architectures/)
assert.match(builderSource, /staging contains unexpected provider architectures/)
assert.match(builderSource, /refusing to remove unmarked staging directory/)
assert.match(builderSource, /npm.*rebuild.*better-sqlite3/)
assert.match(builderSource, /Restoring host Node-native better-sqlite3/)
assert.match(builderSource, /finally \{/)
assert.match(builderSource, /electron-rebuild/)
assert.match(builderSource, /better-sqlite3/)
assert.match(builderSource, /validatePackagedNativeModule/)
assert.match(builderSource, /packaged better_sqlite3\.node architecture does not match/)
assert.match(builderSource, /nativeBuildMayHaveChanged = true/)
assert.match(builderSource, /if \(nativeBuildMayHaveChanged\)/)
assert.match(builderSource, /Restoring host Node-native better-sqlite3/)
assert.match(verifySource, /app\.asar\.unpacked.*better-sqlite3.*better_sqlite3\.node/)
assert.match(verifySource, /packaged better_sqlite3\.node architecture does not match/)
const workflow = readFileSync(join(root, '.github/workflows/release.yml'), 'utf8')
assert.match(workflow, /npm run build:mac:\$\{\{ matrix\.arch \}\}/)
assert.match(workflow, /softprops\/action-gh-release@v2/)
assert.match(workflow, /draft: true/)
assert.match(workflow, /fetch:engines/)
assert.match(workflow, /CHROME_EXTENSION_ID/)
assert.match(workflow, /merge-latest-mac\.mjs/)
assert.match(workflow, /tags: \['v\*'\]/)
assert.doesNotMatch(workflow, /electron-builder --publish always/)
assert.doesNotMatch(workflow, /samuelmeuli\/action-electron-builder/)
const armYml = ['version: 1.1.7', 'files:', '  - url: V-Download-1.1.7-arm64-mac.zip', '    sha512: arm', '    size: 10', 'path: V-Download-1.1.7-arm64-mac.zip', 'sha512: arm', "releaseDate: '2026-01-01T00:00:00.000Z'", ''].join('\n')
const intelYml = ['version: 1.1.7', 'files:', '  - url: V-Download-1.1.7-x64-mac.zip', '    sha512: intel', '    size: 11', 'path: V-Download-1.1.7-x64-mac.zip', 'sha512: intel', "releaseDate: '2026-01-02T00:00:00.000Z'", ''].join('\n')
const merged = mergeLatestMac([parseLatestMac(armYml), parseLatestMac(intelYml)])
assert.equal(merged.version, '1.1.7')
assert.deepEqual(merged.files.map((file) => file.url), ['V-Download-1.1.7-arm64-mac.zip', 'V-Download-1.1.7-x64-mac.zip'])
assert.equal(merged.path, 'V-Download-1.1.7-arm64-mac.zip')
assert.equal(merged.releaseDate, '2026-01-02T00:00:00.000Z')
const mergeDir = mkdtempSync(join(tmpdir(), 'v-download-merge-latest-mac-'))
writeFileSync(join(mergeDir, 'arm.yml'), armYml)
writeFileSync(join(mergeDir, 'intel.yml'), intelYml)
const mergedPath = join(mergeDir, 'out', 'latest-mac.yml')
const mergeRun = spawnSync(process.execPath, [join(root, 'scripts/merge-latest-mac.mjs'), '--out', mergedPath, join(mergeDir, 'arm.yml'), join(mergeDir, 'intel.yml')], { encoding: 'utf8' })
assert.equal(mergeRun.status, 0, mergeRun.stderr)
assert.match(readFileSync(mergedPath, 'utf8'), /V-Download-1\.1\.7-arm64-mac\.zip/)
assert.match(readFileSync(mergedPath, 'utf8'), /V-Download-1\.1\.7-x64-mac\.zip/)
assert.equal(stringifyLatestMac(parseLatestMac(armYml)).includes('version: 1.1.7'), true)
rmSync(mergeDir, { recursive: true, force: true })
console.log('release workflow and latest-mac.yml merge fixtures passed')
